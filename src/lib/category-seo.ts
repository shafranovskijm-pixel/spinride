export function getCategorySEO(category?: CategorySEOInput | null) {
  if (!category) {
    return {
      title: "Каталог велосипедов и самокатов в Уссурийске",
      heading: "Каталог",
      description: "Каталог SPINRIDE в Уссурийске: велосипеды, самокаты, детский транспорт, коньки, тюбинги и запчасти. Сравните цены и характеристики товаров.",
      introduction: "Велосипеды, самокаты и товары для активного отдыха в Уссурийске. Выберите раздел, чтобы сравнить модели, цены и характеристики.",
      guidance: "Наличие и описание смотрите в карточке товара. Если нужна помощь с размером или совместимостью, свяжитесь с магазином перед заказом.",
    };
  }

  const name = category.name.trim();
  const heading = `${name} в Уссурийске`;
  if (category.count === 0) {
    return {
      title: heading,
      heading,
      description: `${name} — раздел каталога SPINRIDE в Уссурийске. Сейчас товаров в этой категории нет. Посмотрите доступные разделы каталога.`,
      introduction: "В этой категории пока нет товаров. Посмотрите другие разделы каталога или уточните ассортимент у магазина.",
      guidance: "",
    };
  }

  const copy = CATEGORY_COPY[category.slug];
  return {
    title: copy?.heading ?? heading,
    heading: copy?.heading ?? heading,
    description: copy?.description ?? `${name} в Уссурийске — каталог SPINRIDE. Сравните цены, фотографии и характеристики товаров.`,
    introduction: copy?.introduction ?? category.description?.trim() ?? `Выберите ${name.toLowerCase()} в каталоге SPINRIDE.`,
    guidance: copy?.guidance ?? "Сравните характеристики и цены в карточках товаров. Неуказанные параметры уточните у магазина перед заказом.",
  };
}

export function getAvailableCategoryLinks<T extends CategorySEOInput>(
  categories: T[],
  currentSlug?: string,
) {
  return categories.filter((category) => (category.count ?? 0) > 0 && category.slug !== currentSlug);
}
